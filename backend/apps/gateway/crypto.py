"""Encrypt gateway secrets at rest (Fernet: AES-128-CBC + HMAC-SHA256).

Set FIELD_ENCRYPTION_KEY (a Fernet key, or any long random string) in production. Without it, a key is derived
from SECRET_KEY, which is fine for development but means rotating SECRET_KEY makes stored secrets unreadable.
"""

import base64
import hashlib

from cryptography.fernet import Fernet, InvalidToken
from django.conf import settings


def _derive(text: str) -> bytes:
    return base64.urlsafe_b64encode(hashlib.sha256(("vargani-fields:" + text).encode()).digest())


def _fernet() -> Fernet:
    key = getattr(settings, "FIELD_ENCRYPTION_KEY", "")
    if not key:
        return Fernet(_derive(settings.SECRET_KEY))
    try:
        return Fernet(key)
    except ValueError:
        # Not a Fernet key, e.g. a random value generated by the hosting platform: derive one from it.
        return Fernet(_derive(key))


def encrypt(value: str) -> str:
    return _fernet().encrypt(value.encode()).decode() if value else ""


def decrypt(value: str) -> str:
    if not value:
        return ""
    try:
        return _fernet().decrypt(value.encode()).decode()
    except InvalidToken:
        return ""
