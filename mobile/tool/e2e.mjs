const shot = async (name) => { await p.waitForTimeout(1200); await p.screenshot({ path: `${String(++n).padStart(2,'0')}-${name}.png` }); console.log('shot', name); };
const sem = async () => { const ph = p.locator('flt-semantics-placeholder'); if (await ph.count()) await ph.evaluate(e => e.click()); await p.waitForTimeout(500); };
const fill = async (label, value) => { const f = p.getByLabel(label, { exact: false }).first(); await f.click(); await f.fill(value); };
const nav = async (text) => { await p.getByRole('tab', { name: new RegExp(text) }).first().click(); await p.waitForTimeout(1200); };
const tap = async (text) => { const btn = p.getByRole('button', { name: new RegExp(text) }); const el = (await btn.count()) ? btn.first() : p.getByText(text).first(); await el.click(); await p.waitForTimeout(1000); };
