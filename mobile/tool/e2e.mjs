import { chromium } from 'playwright';
import { dump } from './dump.mjs';
const b = await chromium.launch({args:['--enable-unsafe-swiftshader','--use-angle=swiftshader']});
const ctx = await b.newContext({ viewport: { width: 412, height: 860 }, locale: 'en-IN' });
const p = await ctx.newPage();
ctx.on('request', r => { const u = r.url(); if (u.includes('wa.me') || u.startsWith('blob:')) console.log('opened:', decodeURIComponent(u).slice(0, 220)); });
p.on('pageerror', e => console.log('pageerror:', e.message));
